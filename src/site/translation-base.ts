export const translateWithDictionary = (value: string, english: Record<string, string>): string => {
  if (english[value] !== undefined) return english[value];
  const trimmed = value.trim();
  if (english[trimmed] !== undefined) return value.replace(trimmed, english[trimmed]);
  return value
    .replace(/，|、/g, ', ')
    .replace(/。/g, '.')
    .replace(/；/g, '; ')
    .replace(/：/g, ': ')
    .replace(/！/g, '!')
    .replace(/？/g, '?');
};
